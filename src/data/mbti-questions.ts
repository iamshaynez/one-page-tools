/** 轮转编排：每轮按 EI→SN→TF→JP 各取一题，任意相邻四题四维各一 */
function interleave(pool: Record<Dim, Question[]>): Question[] {
  const dims: Dim[] = ['EI', 'SN', 'TF', 'JP'];
  const rounds = Math.max(...dims.map((d) => pool[d].length));
  const out: Question[] = [];
  for (let r = 0; r < rounds; r++) {
    for (const d of dims) {
      const q = pool[d][r];
      if (q) out.push(q);
    }
  }
  return out;
}

